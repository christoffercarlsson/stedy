    fn calculate_code<H: Hasher>(key: &[u8], message: &[u8]) -> H::Output {
        let mut mac = Hmac::<H>::new(key);
        mac.update(message);
        mac.finalize()
    }

    fn verify_code<H: Hasher>(key: &[u8], message: &[u8], code: &H::Output) -> bool {
        let mut mac = Hmac::<H>::new(key);
        mac.update(message);
        mac.verify(code)
    }

